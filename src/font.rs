//! Lazy TTF metrics and individual outlines; never preprocess an entire font.
use luma_vector_geometry::lyon_tessellation::{
    math::point,
    path::{Path, path::Builder},
};
use owned_ttf_parser::{AsFaceRef, GlyphId, OutlineBuilder, OwnedFace};

pub struct Font {
    face: OwnedFace,
}

pub struct LineMetrics {
    pub ascent: f32,
    pub descent: f32,
}

pub struct Metrics {
    pub advance_width: f32,
}

impl Font {
    pub fn from_bytes(bytes: Vec<u8>) -> Result<Self, String> {
        OwnedFace::from_vec(bytes, 0)
            .map(|face| Self { face })
            .map_err(|e| e.to_string())
    }

    pub fn lookup_glyph_index(&self, character: char) -> u16 {
        self.face
            .as_face_ref()
            .glyph_index(character)
            .map_or(0, |id| id.0)
    }

    pub fn horizontal_line_metrics(&self, size: f32) -> Option<LineMetrics> {
        let face = self.face.as_face_ref();
        let scale = size / f32::from(face.units_per_em());
        Some(LineMetrics {
            ascent: f32::from(face.ascender()) * scale,
            descent: f32::from(face.descender()) * scale,
        })
    }

    pub fn metrics(&self, character: char, size: f32) -> Metrics {
        let face = self.face.as_face_ref();
        let glyph = GlyphId(self.lookup_glyph_index(character));
        Metrics {
            advance_width: f32::from(face.glyph_hor_advance(glyph).unwrap_or(0)) * size
                / f32::from(face.units_per_em()),
        }
    }

    pub fn horizontal_kern(&self, left: char, right: char, size: f32) -> Option<f32> {
        let face = self.face.as_face_ref();
        let left = face.glyph_index(left)?;
        let right = face.glyph_index(right)?;
        for table in face.tables().kern?.subtables {
            if table.horizontal
                && !table.has_cross_stream
                && let Some(value) = table.glyphs_kerning(left, right)
            {
                return Some(f32::from(value) * size / f32::from(face.units_per_em()));
            }
        }
        None
    }

    /// A character's outline in em units (y down), or `None` for glyphs without one (space).
    #[cfg(test)]
    pub fn outline(&self, character: char) -> Option<Path> {
        self.glyph_outline(self.lookup_glyph_index(character))
    }

    /// A glyph's outline in em units (y down), or `None` for glyphs without one (space).
    pub fn glyph_outline(&self, glyph: u16) -> Option<Path> {
        let face = self.face.as_face_ref();
        let mut outline = GlyphOutline {
            builder: Path::builder(),
            scale: 1. / f32::from(face.units_per_em()),
            open: false,
        };
        face.outline_glyph(GlyphId(glyph), &mut outline)?;
        if outline.open {
            outline.builder.end(true);
        }
        Some(outline.builder.build())
    }
}

struct GlyphOutline {
    builder: Builder,
    scale: f32,
    open: bool,
}

impl OutlineBuilder for GlyphOutline {
    fn move_to(&mut self, x: f32, y: f32) {
        if self.open {
            self.builder.end(true);
        }
        self.builder.begin(point(x * self.scale, -y * self.scale));
        self.open = true;
    }
    fn line_to(&mut self, x: f32, y: f32) {
        self.builder.line_to(point(x * self.scale, -y * self.scale));
    }
    fn quad_to(&mut self, x1: f32, y1: f32, x: f32, y: f32) {
        self.builder.quadratic_bezier_to(
            point(x1 * self.scale, -y1 * self.scale),
            point(x * self.scale, -y * self.scale),
        );
    }
    fn curve_to(&mut self, x1: f32, y1: f32, x2: f32, y2: f32, x: f32, y: f32) {
        self.builder.cubic_bezier_to(
            point(x1 * self.scale, -y1 * self.scale),
            point(x2 * self.scale, -y2 * self.scale),
            point(x * self.scale, -y * self.scale),
        );
    }
    fn close(&mut self) {
        if self.open {
            self.builder.end(true);
            self.open = false;
        }
    }
}

#[cfg(test)]
mod tests {
    use luma_vector_geometry::raster;

    #[test]
    fn inter_glyphs_rasterise_without_seams_strays_or_holes() {
        // The generated Inter instances exist after `pnpm assets` (CI runs tests before it;
        // the synthetic overlapping-contour tests in vector-geometry always run).
        for (file, size) in [
            // The greeting (Title 2) and body text at the TV's density of 1, and Title 1 at 4K.
            ("font-display-650.ttf", 57.),
            ("font-500.ttf", 29.),
            ("font-display-650.ttf", 152.),
        ] {
            let path = format!("{}/.build/assets/{file}", env!("CARGO_MANIFEST_DIR"));
            let Ok(bytes) = std::fs::read(&path) else {
                eprintln!("Skipped: {path} is generated by pnpm assets");
                continue;
            };
            let font = super::Font::from_bytes(bytes).unwrap();
            for character in ['n', 'm', 'e', 'G', 'o', 'a', 's', 'g', 'H', '8'] {
                let outline = font.outline(character).unwrap();
                let bitmap = raster::rasterize(&outline, size);
                let reference = raster::reference_coverage(&outline, size, &bitmap, 16);
                for (index, (&got, want)) in bitmap.data.iter().zip(&reference).enumerate() {
                    let got = got as f32 / 255.;
                    let at = (index as u32 % bitmap.width, index as u32 / bitmap.width);
                    // Fully inside: opaque (no seam where overlapping contours meet).
                    if *want == 1. {
                        assert!(got > 0.95, "{file} {character}: hole {got} at {at:?}");
                    }
                    // Fully outside: nothing (no spikes at sharp corners).
                    if *want == 0. {
                        assert!(got < 0.05, "{file} {character}: stray {got} at {at:?}");
                    }
                    // Edges within both samplings' error of exact box-filtered coverage: the
                    // 16 x 16 point-sampled reference alone can be 1/16 off at a shallow edge.
                    assert!(
                        (got - want).abs() < 0.08,
                        "{file} {character}: {got} vs {want} at {at:?}"
                    );
                }
            }
        }
    }
}
